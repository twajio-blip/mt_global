<?php

namespace App\Http\Controllers\Auth;

use App\Http\Controllers\Controller;
use App\Models\User;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Str;

class SsoController extends Controller
{
    /**
     * Generate a single-use SSO token / login URL for the website builder admin.
     * Authenticated via API Key (X-API-KEY or Bearer token).
     */
    public function generateToken(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'email' => 'nullable|email',
            'redirect_to' => 'nullable|string',
        ]);

        $email = $validated['email'] ?? null;
        $user = null;

        if ($email) {
            $user = User::where('email', $email)->first();
        }

        if (!$user) {
            // Default to primary administrator
            $user = User::where('role', 'admin')->first()
                ?? User::where('email', 'admin@jobportal.com')->first()
                ?? User::first();
        }

        if (!$user) {
            return response()->json([
                'success' => false,
                'message' => 'No admin user found to authenticate.',
            ], 404);
        }

        $token = 'sso_' . Str::random(48);
        $redirectTo = $validated['redirect_to'] ?? '/portal/dashboard';

        // Store single-use token in cache for 5 minutes (300 seconds)
        Cache::put("sso_token_{$token}", [
            'user_id' => $user->id,
            'redirect_to' => $redirectTo,
        ], now()->addMinutes(5));

        $ssoUrl = url("/portal/sso?token={$token}");

        return response()->json([
            'success' => true,
            'message' => 'Single Sign-On URL generated successfully. Valid for 5 minutes.',
            'sso_url' => $ssoUrl,
            'redirect_url' => $ssoUrl,
            'token' => $token,
            'expires_in' => 300,
            'user' => [
                'id' => $user->id,
                'name' => $user->name,
                'email' => $user->email,
                'role' => $user->role,
            ],
        ]);
    }

    /**
     * Consume SSO token or API key in the browser and log the admin in seamlessly.
     */
    public function handle(Request $request): RedirectResponse
    {
        // 1. Single-use token SSO (Generated by website builder backend)
        if ($token = $request->query('token')) {
            $data = Cache::pull("sso_token_{$token}");

            if (!$data || empty($data['user_id'])) {
                return redirect()->route('login')->withErrors([
                    'email' => 'This Single Sign-On link has expired or has already been used. Please try again.',
                ]);
            }

            $user = User::find($data['user_id']);
            if (!$user) {
                return redirect()->route('login')->withErrors([
                    'email' => 'User associated with this SSO session could not be found.',
                ]);
            }

            Auth::login($user, true);
            $request->session()->regenerate();

            $target = $data['redirect_to'] ?? route('portal.dashboard');
            return redirect()->to($target)->with('success', "Welcome back, {$user->name}!");
        }

        // 2. Direct API Key SSO (Instant redirect link configured in website builder env)
        $providedKey = $request->query('key') ?? $request->query('api_key');
        $expectedKey = env('JOB_PORTAL_API_KEY', 'jp_live_sec_99a8b7c6d5e4f3a2b1c0');

        if ($providedKey && hash_equals($expectedKey, (string) $providedKey)) {
            $user = null;
            if ($email = $request->query('email')) {
                $user = User::where('email', $email)->first();
            }

            if (!$user) {
                $user = User::where('role', 'admin')->first()
                    ?? User::where('email', 'admin@jobportal.com')->first()
                    ?? User::first();
            }

            if ($user) {
                Auth::login($user, true);
                $request->session()->regenerate();

                $target = $request->query('redirect_to', route('portal.dashboard'));
                return redirect()->to($target)->with('success', "Logged in via Admin SSO as {$user->name}.");
            }
        }

        return redirect()->route('login')->withErrors([
            'email' => 'Invalid or missing SSO credentials. Please log in manually.',
        ]);
    }
}

